export function normalizeSkiResortSlug(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function findSkiResortBySlug(value: string): SkiResortCatalogItem | null {
  const normalizedSlug = normalizeSkiResortSlug(value);

  return (
    SPAIN_SKI_RESORTS.find((resort) => {
      const aliases = resort.aliases || [];
      return (
        resort.slug === normalizedSlug ||
        aliases.map(normalizeSkiResortSlug).includes(normalizedSlug)
      );
    }) || null
  );
}
